-- =====================================================================
-- Shared practice schema: company + e-commerce (PostgreSQL)
-- Created on Day 1, reused and extended on later days.
--
-- Run it (safe to re-run: it drops and recreates everything):
--   createdb interview_prep                      -- once
--   psql -d interview_prep -f days/day-01/database/setup.sql
--
-- Today you only need to READ these tables. The constraints (PRIMARY KEY,
-- REFERENCES, CHECK, ...) are explained on Day 4.
-- =====================================================================

DROP TABLE IF EXISTS payments, order_items, orders, products, categories,
                     customers, employees, departments CASCADE;

-- ---------- Company side ----------

CREATE TABLE departments (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(50) NOT NULL UNIQUE,
    location  VARCHAR(50)
);

CREATE TABLE employees (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(50) NOT NULL,
    last_name      VARCHAR(50) NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE,
    salary         NUMERIC(10, 2),
    hire_date      DATE NOT NULL,
    department_id  INT REFERENCES departments (id),   -- NULL = not assigned
    manager_id     INT REFERENCES employees (id)      -- NULL = no manager (self reference)
);

-- ---------- E-commerce side ----------

CREATE TABLE customers (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL UNIQUE,
    city        VARCHAR(50),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE categories (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE products (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    category_id  INT NOT NULL REFERENCES categories (id),
    price        NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock        INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    is_active    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE orders (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INT NOT NULL REFERENCES customers (id),
    order_date   TIMESTAMP NOT NULL DEFAULT now(),
    status       VARCHAR(20) NOT NULL
                 CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled'))
);

CREATE TABLE order_items (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    INT NOT NULL REFERENCES orders (id),
    product_id  INT NOT NULL REFERENCES products (id),
    quantity    INT NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10, 2) NOT NULL          -- price at the time of the order
);

CREATE TABLE payments (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id  INT NOT NULL REFERENCES orders (id),
    amount    NUMERIC(10, 2) NOT NULL,
    method    VARCHAR(20) NOT NULL CHECK (method IN ('upi', 'card', 'netbanking', 'cod')),
    status    VARCHAR(20) NOT NULL CHECK (status IN ('success', 'failed', 'refunded')),
    paid_at   TIMESTAMP NOT NULL
);

